import { expect, test } from '@playwright/test';

test('sponsor links, selection, validation and email draft', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.locator('.home-sponsors a')).toHaveCount(12);
  await expect(page.locator('.zipora-footer').getByRole('link', { name: 'Advertise' })).toHaveAttribute('href', '/advertise/');
  await page.locator('.home-sponsors a').last().click();
  await expect(page.getByText('Frame 12 — $30 a month')).toBeVisible();
  await page.goto('/advertise/?frame=5');
  await expect(page.getByText('Frame 5 — $30 a month')).toBeVisible();
  await page.goto('/advertise/?frame=99');
  await expect(page.locator('button[aria-pressed=true]')).toHaveCount(0);
  const submit = page.getByRole('button', { name: /Continue to payment/ });
  await submit.click();
  await expect(page.locator('main').getByRole('alert')).toHaveCount(6);
  await page.getByRole('button', { name: '01 Free Featured' }).click();
  await page.getByLabel('Brand name').fill('Example');
  await page.getByLabel('Tagline').fill('A test tagline');
  await expect(page.getByText('7/16')).toBeVisible();
  await expect(page.getByText('14/25')).toBeVisible();
  await page.getByLabel('Link', { exact: true }).fill('http://example.com');
  await page.getByLabel('Your email').fill('bad');
  await page.getByLabel('Logo', { exact: true }).setInputFiles({ name:'bad.txt', mimeType:'text/plain', buffer:Buffer.from('text') });
  await submit.click();
  await expect(page.getByText('Enter a valid link starting with https://.')).toBeVisible();
  await expect(page.getByText('Enter a valid email address.')).toBeVisible();
  await expect(page.getByText('Choose a valid PNG, JPG, WebP or SVG image.')).toBeVisible();
  await page.getByLabel('Link', { exact: true }).fill('https://example.com');
  await page.getByLabel('Your email').fill('hello@example.com');
  await page.getByLabel('Logo', { exact: true }).setInputFiles({ name:'logo.svg', mimeType:'image/svg+xml', buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48"><rect width="48" height="48"/></svg>') });
  await expect(page.getByRole('img', { name:'Logo preview' })).toBeVisible();
  await submit.click();
  await expect(page.locator('main').getByRole('status')).toContainText('Payment is not connected yet');
  const draft = await page.getByRole('link', { name:'Email contact@zipora.online' }).getAttribute('href');
  expect(decodeURIComponent(draft!)).toContain('Tagline: A test tagline');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.setViewportSize({ width:1440, height:900 });
  await expect(page.getByRole('heading', { level:1 })).toHaveText('Sponsor a frame');
  await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href', 'https://www.zipora.online/advertise/');
});
